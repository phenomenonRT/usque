// BypassSNIs — имена, которые подставляются в TLS SNI. Автор usque отмечает,
// что соединение продолжает работать с любым именем: сертификат сервера не
// проверяется по имени, а привязка идёт к публичному ключу эндпоинта. Поэтому
// ТСПУ, режущее стандартное имя WARP, обходится его заменой.
//
// Сначала идут имена Cloudflare, затем нейтральные имена вне Cloudflare. Они
// нужны, когда провайдер блокирует домены Cloudflare по SNI (тогда первые
// варианты не проходят, а сторонние — проходят). Свои имена можно задать
// флагом --bypass-sni, он полностью заменяет этот список.
var BypassSNIs = []string{
	ConnectSNI,  // consumer-masque.cloudflareclient.com — стандартное
	ZeroTierSNI, // zt-masque.cloudflareclient.com — рекомендует автор usque
	"one.one.one.one",
	"www.cloudflare.com",
	// Нейтральные имена вне Cloudflare (TLS 1.3). Сертификат проверяется по
	// публичному ключу, поэтому подходит любое имя; эти — на случай блокировки
	// доменов Cloudflare целиком.
	"www.microsoft.com",
	"www.apple.com",
	"www.bing.com",
}

